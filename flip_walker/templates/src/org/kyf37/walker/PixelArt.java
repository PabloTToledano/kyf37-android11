    static String[] glyph(char c){return FONT.get(c);} // outer screen
    static String plain(String text){return Normalizer.normalize(text,Normalizer.Form.NFC).toUpperCase(Locale.ROOT).replace('’','\'').replace("…","...");}
    static int scale(float size){return Math.max(1,Math.round(size/9));}
    static float width(String text,float size){return plain(text).length()*6*scale(size);}
    static void text(Canvas c,Paint p,String text,float x,float baseline,float size,int color){
        text=plain(text);int s=scale(size),top=Math.round(baseline)-7*s,ox=Math.round(x);
        p.setColor(color);p.setAntiAlias(false);
        for(int i=0;i<text.length();i++){
            char ch=text.charAt(i);String[] glyph=FONT.get(ch);
            if(glyph==null){if(ch==' ')continue;glyph=FONT.get('?');}
            for(int row=0;row<7;row++)for(int col=0;col<5;col++)if(glyph[row].charAt(col)=='1'){
                int px=ox+i*6*s+col*s,py=top+row*s;c.drawRect(px,py,px+s,py+s,p);
            }
        }
    }
    static void tile(Canvas c,Paint p,String[] image,int x,int y,int s,int[] colors){
        p.setAntiAlias(false);
        for(int row=0;row<image.length;row++)for(int col=0;col<image[row].length();col++){
            int n=image[row].charAt(col)-'0';if(n==0)continue;p.setColor(colors[n]);
            c.drawRect(x+col*s,y+row*s,x+(col+1)*s,y+(row+1)*s,p);
        }
    }
